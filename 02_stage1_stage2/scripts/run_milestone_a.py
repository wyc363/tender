from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from document_processing.parse_planner import build_parse_plan, powershell_command
from document_processing.pdf_scanner import scan_pdf
from document_processing.section_locator import locate_sections


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Run Milestone A over tender PDFs without OCR/MinerU/LLM.")
    parser.add_argument("--pdf-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "outputs")
    parser.add_argument("--review-point", default="regional_industry_award")
    args = parser.parse_args()

    config = yaml.safe_load((ROOT / "configs" / "review_points.yaml").read_text(encoding="utf-8"))
    policy = config["review_points"][args.review_point]
    pdf_paths = sorted(args.pdf_dir.resolve().glob("*.pdf"), key=lambda path: path.name)
    if len(pdf_paths) != 19:
        raise SystemExit(f"Expected exactly 19 PDFs, found {len(pdf_paths)} in {args.pdf_dir}")

    section_dir = args.output_dir / "section_maps"
    plan_dir = args.output_dir / "parse_plans"
    output_root = str((ROOT / "data" / "mineru_raw").resolve())
    commands = [
        "# Generated by Milestone A. Review ranges before execution.",
        "# This script has NOT been executed.",
        "& 'D:\\Anaconda\\shell\\condabin\\conda-hook.ps1'",
        "conda activate mineru",
        "",
    ]
    summary: list[dict[str, object]] = []
    for index, pdf_path in enumerate(pdf_paths, start=1):
        doc_id = f"DOC{index:03d}"
        scan = scan_pdf(pdf_path, doc_id)
        keyword_terms = list(dict.fromkeys(
            policy.get("keyword_index_terms", [])
            + policy.get("qualification_terms", [])
            + policy.get("conditional_reference_terms", [])
        ))
        section_map = locate_sections(scan, keyword_terms)
        plan = build_parse_plan(section_map, args.review_point, policy)
        write_json(section_dir / f"{doc_id}_section_map.json", section_map)
        write_json(plan_dir / f"{doc_id}_parse_plan.json", plan)
        commands.extend([f"# {doc_id}: {pdf_path.name}"])
        if not plan["ranges"]:
            commands.append(f"# MANUAL REVIEW REQUIRED: no target ranges located for {doc_id}")
        for item in plan["ranges"]:
            commands.extend([powershell_command(plan, item, output_root), ""])
        eval_section = next((item for item in section_map["sections"] if item["section_role"] == "EVALUATION"), None)
        summary.append(
            {
                "doc_id": doc_id,
                "file_name": pdf_path.name,
                "page_count": scan["page_count"],
                "evaluation_pdf_pages": [eval_section["pdf_page_start"], eval_section["pdf_page_end"]] if eval_section else None,
                "planned_ranges": len(plan["ranges"]),
                "missing_primary_sections": plan["missing_primary_sections"],
                "missing_required_sections": plan["missing_required_sections"],
                "triggered_sections_found": plan["triggered_sections_found"],
                "conditional_sections_included": plan["conditional_sections_included"],
                "context_on_demand_sections_located": plan["context_on_demand_sections_located"],
                "requires_manual_confirmation": plan["requires_manual_confirmation"],
            }
        )
        print(f"{doc_id}: {pdf_path.name} ({scan['page_count']} pages, {len(plan['ranges'])} ranges)")

    command_path = args.output_dir / "mineru_commands.ps1"
    command_path.parent.mkdir(parents=True, exist_ok=True)
    command_path.write_text("\n".join(commands), encoding="utf-8-sig")
    report = {
        "milestone": "A",
        "pdf_count": len(pdf_paths),
        "review_point": args.review_point,
        "section_map_count": len(list(section_dir.glob("*_section_map.json"))),
        "parse_plan_count": len(list(plan_dir.glob("*_parse_plan.json"))),
        "mineru_commands_generated_only": True,
        "documents": summary,
    }
    write_json(args.output_dir / "milestone_a_summary.json", report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
